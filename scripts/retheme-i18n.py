    start = s.index(f'const {lang}: Dict = {{')
    end = s.index('\n};', start)
    block = s[start:end]
    for key, val in patch.items():
        pat = re.compile(r"^  '" + re.escape(key) + r"': .*$", re.M)
        line = "  '" + key + "': '" + val.replace("'", "\\'") + "',"
        if key == 'acc.flower':
            line = "  'acc.bell': '" + val + "',"
        if not pat.search(block):
            print('MISSING', lang, key)
            continue
        block = pat.sub(lambda m: line, block, count=1)
    s = s[:start] + block + s[end:]

